-- Execute after the candidate/installed migration inside BEGIN / ROLLBACK.
DO $proof$
DECLARE who uuid; other_user uuid; disabled_user uuid; value jsonb; until_at timestamptz;
 request_id uuid:=gen_random_uuid(); protected_before text; protected_after text;
BEGIN
 SELECT user_id INTO STRICT who FROM public.account_access WHERE enabled ORDER BY user_id LIMIT 1;
 SELECT user_id INTO STRICT other_user FROM public.account_access WHERE enabled AND user_id<>who ORDER BY user_id LIMIT 1;
 SELECT user_id INTO STRICT disabled_user FROM public.account_access WHERE NOT enabled ORDER BY user_id LIMIT 1;
 SELECT md5(coalesce(jsonb_agg(to_jsonb(d) ORDER BY user_id)::text,'')) INTO protected_before FROM private.push_defaults d;
 DELETE FROM private.mobile_onboarding WHERE user_id IN(who,other_user);
 PERFORM set_config('request.jwt.claim.sub',who::text,true);
 SET LOCAL ROLE authenticated;
 value:=public.mobile_onboarding_preference();
 IF value->>'eligible'<>'true' THEN RAISE EXCEPTION 'existing missing row not eligible'; END IF;
 BEGIN PERFORM public.mobile_onboarding_preference('read',2);RAISE EXCEPTION 'unknown version accepted';EXCEPTION WHEN invalid_parameter_value THEN NULL;END;
 BEGIN PERFORM public.mobile_onboarding_preference('snooze');RAISE EXCEPTION 'missing request accepted';EXCEPTION WHEN invalid_parameter_value THEN NULL;END;
 BEGIN PERFORM public.mobile_onboarding_preference('reset',1,request_id);RAISE EXCEPTION 'invalid action accepted';EXCEPTION WHEN invalid_parameter_value THEN NULL;END;
 BEGIN PERFORM public.mobile_onboarding_preference('complete',1,request_id,other_user);RAISE EXCEPTION 'stale identity accepted';EXCEPTION WHEN insufficient_privilege THEN NULL;END;
 BEGIN EXECUTE 'SELECT * FROM private.mobile_onboarding';RAISE EXCEPTION 'private data exposed';EXCEPTION WHEN insufficient_privilege THEN NULL;END;
 value:=public.mobile_onboarding_preference('present',1,gen_random_uuid());
 IF value->>'eligible'<>'true' OR value->>'lastPresentedAt' IS NULL THEN RAISE EXCEPTION 'presentation failed'; END IF;
 value:=public.mobile_onboarding_preference('snooze',1,request_id);until_at:=(value->>'snoozedUntil')::timestamptz;
 IF value->>'eligible'<>'false' OR abs(extract(epoch FROM until_at-clock_timestamp()-interval '7 days'))>2 THEN RAISE EXCEPTION 'server seven day snooze failed'; END IF;
 value:=public.mobile_onboarding_preference('snooze',1,request_id);
 IF (value->>'snoozedUntil')::timestamptz<>until_at THEN RAISE EXCEPTION 'retry extended snooze'; END IF;
 value:=public.mobile_onboarding_preference('snooze',1,gen_random_uuid());
 IF (value->>'snoozedUntil')::timestamptz<>until_at THEN RAISE EXCEPTION 'concurrent snooze extended snooze'; END IF;
 RESET ROLE;
 IF (SELECT count(*) FROM private.mobile_onboarding WHERE user_id=who)<>1 THEN RAISE EXCEPTION 'duplicate account/version';END IF;
 UPDATE private.mobile_onboarding SET snoozed_until=clock_timestamp()-interval '1 second' WHERE user_id=who;
 SET LOCAL ROLE authenticated;
 IF public.mobile_onboarding_preference()->>'eligible'<>'true' THEN RAISE EXCEPTION 'expired snooze ineligible';END IF;
 value:=public.mobile_onboarding_preference('complete',1,gen_random_uuid());
 IF value->>'completed'<>'true' OR value->>'eligible'<>'false' THEN RAISE EXCEPTION 'completion failed';END IF;
 value:=public.mobile_onboarding_preference('snooze',1,gen_random_uuid());
 IF value->>'completed'<>'true' OR value->>'eligible'<>'false' THEN RAISE EXCEPTION 'late decision reopened completion';END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',other_user::text,true);
 SET LOCAL ROLE authenticated;
 IF public.mobile_onboarding_preference()->>'eligible'<>'true' THEN RAISE EXCEPTION 'cross-account suppression';END IF;
 value:=public.mobile_onboarding_preference('dismiss',1,gen_random_uuid());
 IF value->>'dismissed'<>'true' OR value->>'eligible'<>'false' THEN RAISE EXCEPTION 'permanent dismissal failed';END IF;
 value:=public.mobile_onboarding_preference('present',1,gen_random_uuid());
 IF value->>'eligible'<>'false' THEN RAISE EXCEPTION 'presentation erased dismissal';END IF;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub',disabled_user::text,true);
 SET LOCAL ROLE authenticated;
 BEGIN PERFORM public.mobile_onboarding_preference();RAISE EXCEPTION 'disabled user authorized';EXCEPTION WHEN insufficient_privilege THEN NULL;END;
 RESET ROLE;
 PERFORM set_config('request.jwt.claim.sub','',true);
 SET LOCAL ROLE authenticated;
 BEGIN PERFORM public.mobile_onboarding_preference();RAISE EXCEPTION 'missing user authorized';EXCEPTION WHEN insufficient_privilege THEN NULL;END;
 RESET ROLE;
 SET LOCAL ROLE anon;
 BEGIN PERFORM public.mobile_onboarding_preference();RAISE EXCEPTION 'anon authorized';EXCEPTION WHEN insufficient_privilege THEN NULL;END;
 RESET ROLE;
 SELECT md5(coalesce(jsonb_agg(to_jsonb(d) ORDER BY user_id)::text,'')) INTO protected_after FROM private.push_defaults d;
 IF protected_before IS DISTINCT FROM protected_after THEN RAISE EXCEPTION 'notification settings changed';END IF;
 IF EXISTS(SELECT FROM pg_stat_xact_user_tables WHERE schemaname='public' AND n_tup_ins+n_tup_upd+n_tup_del>0) THEN RAISE EXCEPTION 'unexpected public state write';END IF;
END $proof$;
SELECT 'PASS: eligibility, server snooze, replay, terminal decisions, isolation, authorization, no public/notification writes' AS onboarding_proof;
