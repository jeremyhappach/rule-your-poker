CREATE FUNCTION private.five_alive_or_actor(c private.delayed_children,p_actor uuid) RETURNS boolean
LANGUAGE plpgsql STABLE SET search_path='' AS $$
DECLARE game jsonb;round_i integer;idx integer;
BEGIN
