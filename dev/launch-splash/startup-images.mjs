// iOS requires launch images at the display's pixel dimensions. These are
// deterministic contain-fit exports of the approved frame, not new artwork.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {chromium} from '@playwright/test';
import {optimizePng} from '../../scripts/storage/png-lossless.mjs';
const displays=[[320,568,2],[375,667,2],[414,736,3],[375,812,3],[390,844,3],
 [393,852,3],[402,874,3],[414,896,2],[414,896,3],[428,926,3],[430,932,3],[440,956,3]];
const out='public/launch-splash/startup';mkdirSync(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage();
 const src='data:image/png;base64,'+readFileSync('public/launch-splash/approved-v1-opening.png').toString('base64');
 const links=[];
 for(const [w,h,scale] of displays)for(const landscape of [false,true]){
  const width=(landscape?h:w)*scale,height=(landscape?w:h)*scale,file=`opening-${width}x${height}.png`;
  const data=await page.evaluate(async({src,width,height})=>{
   const image=new Image();image.src=src;await image.decode();
   const canvas=document.createElement('canvas');canvas.width=width;canvas.height=height;
   const ctx=canvas.getContext('2d');ctx.fillStyle='#020b15';ctx.fillRect(0,0,width,height);
   const fit=Math.min(width/image.width,height/image.height),iw=image.width*fit,ih=image.height*fit;
   ctx.drawImage(image,(width-iw)/2,(height-ih)/2,iw,ih);
   return canvas.toDataURL('image/png').split(',')[1];
  },{src,width,height});
  writeFileSync(out+'/'+file,optimizePng(Buffer.from(data,'base64')).bytes);
  links.push(`    <link rel="apple-touch-startup-image" href="/launch-splash/startup/${file}" media="(device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${scale}) and (orientation: ${landscape?'landscape':'portrait'})" />`);
 }
 const path='index.html',html=readFileSync(path,'utf8'),block='    <!-- iOS launch artwork: generated by dev/launch-splash/startup-images.mjs -->\n'+links.join('\n')+'\n    <!-- /iOS launch artwork -->';
 writeFileSync(path,html.includes('<!-- iOS launch artwork:')?html.replace(/    <!-- iOS launch artwork:[\s\S]*?<!-- \/iOS launch artwork -->/,block):html.replace('    <meta name="application-name"',block+'\n    <meta name="application-name"'));
 console.log(`${links.length} native launch images generated from the unchanged opening frame.`);
}finally{await browser.close();}
